// Package engine renders a catalog template into a kickstart repository.
package engine

import (
	"archive/zip"
	"bytes"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"text/template"

	"github.com/udaykishore-resu/kickhub/internal/catalog"
	"gopkg.in/yaml.v3"
)

// Request is what the user picked.
type Request struct {
	Template string            `json:"template"`
	Target   string            `json:"target"`
	Name     string            `json:"name"`
	Params   map[string]string `json:"params"`
}

// Result is a rendered repository held in memory.
type Result struct {
	Template *catalog.Template
	Target   string
	Name     string
	Params   map[string]string
	Files    map[string][]byte
}

var nameRE = regexp.MustCompile(`^[a-z][a-z0-9-]{1,38}[a-z0-9]$`)

// Templates use [[ ]] so they never collide with GitHub Actions ${{ }},
// Terraform ${ } or Helm {{ }} inside the generated files.
func newTemplate(name string) *template.Template {
	return template.New(name).Delims("[[", "]]").Option("missingkey=error").Funcs(template.FuncMap{
		"snake": func(s string) string { return strings.ReplaceAll(s, "-", "_") },
		"upper": strings.ToUpper,
	})
}

func renderString(name, text string, data any) (string, error) {
	t, err := newTemplate(name).Parse(text)
	if err != nil {
		return "", err
	}
	var b bytes.Buffer
	if err := t.Execute(&b, data); err != nil {
		return "", err
	}
	return b.String(), nil
}

// Render validates the request and renders every file of the template.
func Render(c *catalog.Catalog, req Request) (*Result, error) {
	t, ok := c.Get(req.Template)
	if !ok {
		return nil, fmt.Errorf("unknown template %q", req.Template)
	}
	if !nameRE.MatchString(req.Name) {
		return nil, fmt.Errorf("name %q must be 3-40 chars of lowercase letters, digits and dashes, starting with a letter", req.Name)
	}
	layers, err := t.Layers(req.Target)
	if err != nil {
		return nil, err
	}

	known := map[string]bool{}
	params := map[string]string{}
	ctx := map[string]any{"Name": req.Name, "Target": req.Target, "Template": t.ID, "Version": t.Version, "P": params}
	for _, p := range t.Parameters {
		known[p.Name] = true
		if !p.AppliesTo(req.Target) {
			params[p.Name] = "" // keeps shared files renderable for every target
			continue
		}
		v := strings.TrimSpace(req.Params[p.Name])
		if v == "" {
			if v, err = renderString(p.Name, p.Default, ctx); err != nil {
				return nil, fmt.Errorf("default for %q: %w", p.Name, err)
			}
		}
		if v == "" && p.Required {
			return nil, fmt.Errorf("parameter %q is required for target %q (%s)", p.Name, req.Target, p.Description)
		}
		if strings.ContainsAny(v, "\n\r\"`") {
			return nil, fmt.Errorf("parameter %q contains quotes or newlines", p.Name)
		}
		params[p.Name] = v
	}
	for k := range req.Params {
		if !known[k] {
			return nil, fmt.Errorf("unknown parameter %q for template %q", k, t.ID)
		}
	}

	res := &Result{Template: t, Target: req.Target, Name: req.Name, Params: params, Files: map[string][]byte{}}
	for _, layer := range layers {
		if _, err := fs.Stat(t.FS, layer); err != nil {
			continue // a target may add no files of its own
		}
		err := fs.WalkDir(t.FS, layer, func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return err
			}
			raw, err := fs.ReadFile(t.FS, p)
			if err != nil {
				return err
			}
			rel, err := renderString(p, strings.TrimSuffix(strings.TrimPrefix(p, layer+"/"), ".tmpl"), ctx)
			if err != nil {
				return fmt.Errorf("%s: %w", p, err)
			}
			rel = path.Clean(rel)
			if rel == "." || strings.HasPrefix(rel, "../") || path.IsAbs(rel) {
				return fmt.Errorf("%s: renders to an unsafe path %q", p, rel)
			}
			body, err := renderString(p, string(raw), ctx)
			if err != nil {
				return fmt.Errorf("%s: %w", p, err)
			}
			res.Files[rel] = []byte(body) // later layers override earlier ones
			return nil
		})
		if err != nil {
			return nil, err
		}
	}

	// Lockfile: records exactly how the repo was produced, so it can be
	// regenerated or diffed against a newer template version later.
	used := map[string]string{}
	for k, v := range params {
		if v != "" {
			used[k] = v
		}
	}
	lock, err := yaml.Marshal(map[string]any{
		"template": t.ID, "version": t.Version, "target": req.Target, "name": req.Name, "params": used,
	})
	if err != nil {
		return nil, err
	}
	res.Files[".kickhub.yaml"] = append([]byte("# Generated by kickhub. Records how this repo was created.\n"), lock...)
	return res, nil
}

// Paths returns the rendered file paths, sorted.
func (r *Result) Paths() []string {
	out := make([]string, 0, len(r.Files))
	for p := range r.Files {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

// WriteDir writes the repository to dir, which must be missing or empty.
func (r *Result) WriteDir(dir string) error {
	if entries, err := os.ReadDir(dir); err == nil && len(entries) > 0 {
		return fmt.Errorf("%s already exists and is not empty", dir)
	}
	for _, p := range r.Paths() {
		full := filepath.Join(dir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(full, r.Files[p], 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Zip writes the repository as a zip archive under a single root folder.
func (r *Result) Zip(w io.Writer) error {
	zw := zip.NewWriter(w)
	for _, p := range r.Paths() {
		f, err := zw.Create(r.Name + "/" + p)
		if err != nil {
			return err
		}
		if _, err := f.Write(r.Files[p]); err != nil {
			return err
		}
	}
	return zw.Close()
}

// Check is the result of looking for one required CLI tool.
type Check struct {
	Tool  string `json:"tool"`
	Found bool   `json:"found"`
}

// Doctor reports which tools the target needs are present on PATH.
func Doctor(t *catalog.Template, target string) ([]Check, error) {
	tg, ok := t.Targets[target]
	if !ok {
		return nil, fmt.Errorf("template %q has no target %q", t.ID, target)
	}
	var out []Check
	for _, tool := range tg.Requires {
		_, err := exec.LookPath(tool)
		out = append(out, Check{Tool: tool, Found: err == nil})
	}
	return out, nil
}
