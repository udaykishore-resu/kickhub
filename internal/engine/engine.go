// Package engine renders a catalog template into a kickstart repository.
package engine

import (
	"archive/zip"
	"bytes"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"text/template"

	"github.com/udaykishore-resu/kickhub/internal/catalog"
	"gopkg.in/yaml.v3"
)

// LockFile records how a repository was generated.
const LockFile = ".kickhub.yaml"

// Request is what the user picked.
type Request struct {
	Template string            `json:"template" yaml:"template"`
	Target   string            `json:"target" yaml:"target"`
	Name     string            `json:"name" yaml:"name"`
	Params   map[string]string `json:"params" yaml:"params"`
}

// Result is a rendered repository held in memory.
type Result struct {
	Template *catalog.Template
	Target   string
	Name     string
	Params   map[string]string
	Files    map[string][]byte
}

var nameRE = regexp.MustCompile(`^[a-z][a-z0-9-]{1,38}[a-z0-9]$`)

// Templates use [[ ]] so they never collide with GitHub Actions ${{ }},
// Terraform ${ } or Helm {{ }} inside the generated files.
func newTemplate(name string) *template.Template {
	return template.New(name).Delims("[[", "]]").Option("missingkey=error").Funcs(template.FuncMap{
		"snake": func(s string) string { return strings.ReplaceAll(s, "-", "_") },
		"upper": strings.ToUpper,
	})
}

func renderString(name, text string, data any) (string, error) {
	t, err := newTemplate(name).Parse(text)
	if err != nil {
		return "", err
	}
	var b bytes.Buffer
	if err := t.Execute(&b, data); err != nil {
		return "", err
	}
	return b.String(), nil
}

// Render validates the request and renders every file of the template.
func Render(c *catalog.Catalog, req Request) (*Result, error) {
	t, ok := c.Get(req.Template)
	if !ok {
		return nil, fmt.Errorf("unknown template %q", req.Template)
	}
	if !nameRE.MatchString(req.Name) {
		return nil, fmt.Errorf("name %q must be 3-40 chars of lowercase letters, digits and dashes, starting with a letter", req.Name)
	}
	target, ok := t.ResolveTarget(req.Target)
	if !ok {
		return nil, fmt.Errorf("template %q does not support target %q", t.ID, req.Target)
	}
	layers, err := t.Layers(target)
	if err != nil {
		return nil, err
	}
	tg := t.Targets[target]

	known := map[string]bool{}
	params := map[string]string{}
	ctx := map[string]any{
		"Name": req.Name, "Target": target, "Template": t.ID, "Version": t.Version,
		"Title": t.Name, "Description": t.Description, "Summary": tg.Summary, "Resources": tg.Resources,
		"Notes": "", "P": params, "V": t.Vars,
	}
	for _, p := range t.Parameters {
		known[p.Name] = true
		if !p.AppliesTo(target) {
			params[p.Name] = "" // keeps shared files renderable for every target
			continue
		}
		v := strings.TrimSpace(req.Params[p.Name])
		if v == "" {
			if v, err = renderString(p.Name, p.Default, ctx); err != nil {
				return nil, fmt.Errorf("default for %q: %w", p.Name, err)
			}
		}
		if v == "" && p.Required {
			return nil, fmt.Errorf("parameter %q is required for target %q (%s)", p.Name, target, p.Description)
		}
		if strings.ContainsAny(v, "\n\r\"`") {
			return nil, fmt.Errorf("parameter %q contains quotes or newlines", p.Name)
		}
		params[p.Name] = v
	}
	for k := range req.Params {
		if !known[k] {
			return nil, fmt.Errorf("unknown parameter %q for template %q", k, t.ID)
		}
	}
	if ctx["Notes"], err = renderString("notes", tg.Notes, ctx); err != nil {
		return nil, fmt.Errorf("notes for target %q: %w", target, err)
	}

	res := &Result{Template: t, Target: target, Name: req.Name, Params: params, Files: map[string][]byte{}}
	for _, layer := range layers {
		err := fs.WalkDir(layer.FS, layer.Dir, func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return err
			}
			raw, err := fs.ReadFile(layer.FS, p)
			if err != nil {
				return err
			}
			rel, err := renderString(p, strings.TrimSuffix(strings.TrimPrefix(p, layer.Dir+"/"), ".tmpl"), ctx)
			if err != nil {
				return fmt.Errorf("%s: %w", p, err)
			}
			rel = path.Clean(rel)
			if rel == "." || strings.HasPrefix(rel, "../") || path.IsAbs(rel) {
				return fmt.Errorf("%s: renders to an unsafe path %q", p, rel)
			}
			body, err := renderString(p, string(raw), ctx)
			if err != nil {
				return fmt.Errorf("%s: %w", p, err)
			}
			if strings.TrimSpace(body) == "" {
				delete(res.Files, rel) // a file that renders empty is left out
				return nil
			}
			res.Files[rel] = []byte(body) // later layers override earlier ones
			return nil
		})
		if err != nil {
			return nil, err
		}
	}

	// Lockfile: records exactly how the repo was produced, so `kickhub status`
	// can later tell what drifted from the template.
	used := map[string]string{}
	for k, v := range params {
		if v != "" {
			used[k] = v
		}
	}
	lock, err := yaml.Marshal(map[string]any{
		"template": t.ID, "version": t.Version, "target": target, "name": req.Name, "params": used,
	})
	if err != nil {
		return nil, err
	}
	res.Files[LockFile] = append([]byte("# Generated by kickhub. Records how this repo was created.\n"), lock...)
	return res, nil
}

// Paths returns the rendered file paths, sorted.
func (r *Result) Paths() []string {
	out := make([]string, 0, len(r.Files))
	for p := range r.Files {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

// WriteDir writes the repository to dir. Without merge, dir must be missing
// or empty. With merge, files are added to an existing repository and any
// file already present is left untouched and returned in skipped.
func (r *Result) WriteDir(dir string, merge bool) (skipped []string, err error) {
	if entries, rerr := os.ReadDir(dir); !merge && rerr == nil && len(entries) > 0 {
		return nil, fmt.Errorf("%s already exists and is not empty (use -into to add to an existing repo)", dir)
	}
	for _, p := range r.Paths() {
		full := filepath.Join(dir, filepath.FromSlash(p))
		if merge {
			if _, serr := os.Stat(full); serr == nil {
				skipped = append(skipped, p)
				continue
			}
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return skipped, err
		}
		if err := os.WriteFile(full, r.Files[p], 0o644); err != nil {
			return skipped, err
		}
	}
	return skipped, nil
}

// Zip writes the repository as a zip archive under a single root folder.
func (r *Result) Zip(w io.Writer) error {
	zw := zip.NewWriter(w)
	for _, p := range r.Paths() {
		f, err := zw.Create(r.Name + "/" + p)
		if err != nil {
			return err
		}
		if _, err := f.Write(r.Files[p]); err != nil {
			return err
		}
	}
	return zw.Close()
}

// Drift is how a generated repository differs from its template today.
type Drift struct {
	Request        Request
	LockedVersion  string
	CurrentVersion string
	Unchanged      int
	Modified       []string // edited since generation, or changed in a newer template
	Missing        []string // deleted locally, or added by a newer template
}

// Status re-renders the template recorded in dir's lockfile and compares it
// with the files on disk.
func Status(c *catalog.Catalog, dir string) (*Drift, error) {
	raw, err := os.ReadFile(filepath.Join(dir, LockFile))
	if err != nil {
		return nil, fmt.Errorf("%s was not generated by kickhub: %w", dir, err)
	}
	var lock struct {
		Request `yaml:",inline"`
		Version string `yaml:"version"`
	}
	if err := yaml.Unmarshal(raw, &lock); err != nil {
		return nil, fmt.Errorf("%s: %w", LockFile, err)
	}
	res, err := Render(c, lock.Request)
	if err != nil {
		return nil, err
	}
	d := &Drift{Request: lock.Request, LockedVersion: lock.Version, CurrentVersion: res.Template.Version}
	for _, p := range res.Paths() {
		if p == LockFile {
			continue
		}
		disk, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(p)))
		switch {
		case err != nil:
			d.Missing = append(d.Missing, p)
		case bytes.Equal(disk, res.Files[p]):
			d.Unchanged++
		default:
			d.Modified = append(d.Modified, p)
		}
	}
	return d, nil
}

// Check is the result of looking for one required CLI tool.
type Check struct {
	Tool  string `json:"tool"`
	Found bool   `json:"found"`
}

// Doctor reports which tools the target needs are present on PATH.
func Doctor(t *catalog.Template, target string) ([]Check, error) {
	target, ok := t.ResolveTarget(target)
	if !ok {
		return nil, fmt.Errorf("template %q does not support that target", t.ID)
	}
	var out []Check
	for _, tool := range t.Targets[target].Requires {
		_, err := exec.LookPath(tool)
		out = append(out, Check{Tool: tool, Found: err == nil})
	}
	return out, nil
}
